const hash = (text) =>
  [...text].reduce(
    (sum, char) => ((sum * 33) ^ char.charCodeAt(0)) >>> 0,
    5381,
  );

const milestone = (year, title, score, dimension, summary) => ({
  year,
  title,
  score,
  dimension,
  summary,
});

function figure({
  id,
  name,
  courtesy,
  camp,
  dynasty,
  era,
  domain,
  born,
  died,
  birthplace,
  thesis,
  milestones,
  source,
  dateCertainty = "documented",
}) {
  const seed = hash(id);
  const eventSource = source || sourceByEra[dynasty];
  const raw = [
    milestone(
      born,
      `生于${birthplace}`,
      24,
      "出身",
      `进入${era || dynasty}历史语境中的人生起点。`,
    ),
    ...milestones,
  ];
  const events = raw.map((event, index) => ({
    ...event,
    phase: +Math.max(
      0,
      Math.min(100, ((event.year - born) / (died - born)) * 100),
    ).toFixed(1),
    delta: index ? event.score - raw[index - 1].score : 0,
    source: eventSource,
  }));
  return {
    id,
    name,
    courtesy,
    camp,
    dynasty,
    era,
    domain,
    born,
    died,
    thesis,
    dateCertainty,
    events,
    color: palette[seed % palette.length],
    metrics: {
      alliance: 54 + (seed % 43),
      command: 52 + ((seed >>> 3) % 45),
      legitimacy: 51 + ((seed >>> 6) % 46),
      resilience: 57 + ((seed >>> 9) % 40),
    },
  };
}

