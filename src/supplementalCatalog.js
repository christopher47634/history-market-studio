import { sourceByEra } from "./catalog.js";

const palette = ["#b85a4d", "#397b70", "#a77747", "#57758e", "#7d614d", "#536f61", "#875268", "#686a96"];
const hash = (text) => [...text].reduce((sum, char) => ((sum * 31) + char.charCodeAt(0)) >>> 0, 17);
const m = (year, title, score, dimension, summary) => ({ year, title, score, dimension, summary });

function person({ id, name, courtesy, camp, dynasty, born, died, thesis, milestones, domain }) {
  const seed = hash(id);
  const source = sourceByEra[dynasty];
  const raw = [
    m(born, `生于${camp}`, 24, "出身", `进入${dynasty}历史语境中的人生起点。`),
    ...milestones,
    m(died, "人生终章", 0, "终局", "个人生命结束，影响进入后世评价阶段。"),
  ];
  const events = raw.map((event, index) => ({
    ...event,
    phase: +Math.max(0, Math.min(100, ((event.year - born) / (died - born)) * 100)).toFixed(1),
    delta: index ? event.score - raw[index - 1].score : 0,
    source,
  }));
  return {
    id, name, courtesy, camp, dynasty, born, died, thesis, domain, events,
    color: palette[seed % palette.length],
    metrics: {
      alliance: 55 + (seed % 42),
      command: 51 + ((seed >>> 3) % 46),
      legitimacy: 53 + ((seed >>> 6) % 44),
      resilience: 58 + ((seed >>> 9) % 39),
    },
  };
}

